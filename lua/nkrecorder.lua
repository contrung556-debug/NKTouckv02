-- Converts ZXTouch raw HID recording files into editable NKTouch Lua scripts.

local VERSION = "0.7.1"
local TAP_MOVE_THRESHOLD = 18.0
local HOLD_THRESHOLD_MS = 450
local MAX_ACTION_MS = 300000

local function round(n)
  return math.floor((tonumber(n) or 0) + 0.5)
end

local function dist(x1, y1, x2, y2)
  local dx, dy = x2 - x1, y2 - y1
  return math.sqrt(dx * dx + dy * dy)
end

local function clean_comment(s)
  return tostring(s or ""):gsub("[\r\n]", " ")
end

local function parse_raw(path)
  local f, err = io.open(path, "r")
  if not f then return nil, "cannot open raw file: " .. tostring(err) end

  local gestures, active = {}, {}
  local pending_us, ignored = 0, 0

  for rawline in f:lines() do
    local line = rawline:gsub("%s+$", "")
    local sleep_us = line:match("^18(%d+)$")
    if sleep_us then
      pending_us = pending_us + (tonumber(sleep_us) or 0)
    else
      local kind, finger, xs, ys = line:match("^101([012])(%d%d)(%d%d%d%d%d)(%d%d%d%d%d)$")
      if kind then
        local x, y = tonumber(xs) / 10.0, tonumber(ys) / 10.0
        if kind == "1" then
          if active[finger] then ignored = ignored + 1 end
          active[finger] = {
            finger = finger,
            x1 = x, y1 = y, x2 = x, y2 = y,
            idle_us = pending_us,
            duration_us = 0,
            points = 1,
            max_distance = 0,
          }
        else
          local g = active[finger]
          if not g then
            ignored = ignored + 1
          else
            g.duration_us = g.duration_us + pending_us
            g.x2, g.y2 = x, y
            g.points = g.points + 1
            g.max_distance = math.max(g.max_distance, dist(g.x1, g.y1, x, y))
            if kind == "0" then
              local duration_ms = math.max(1, round(g.duration_us / 1000.0))
              local idle_ms = math.max(0, round(g.idle_us / 1000.0))
              if #gestures == 0 then idle_ms = 0 end

              local action
              if g.max_distance <= TAP_MOVE_THRESHOLD then
                if duration_ms >= HOLD_THRESHOLD_MS then action = "hold" else action = "tap" end
              else
                action = "swipe"
              end

              gestures[#gestures + 1] = {
                action = action,
                x1 = g.x1, y1 = g.y1, x2 = g.x2, y2 = g.y2,
                idle_ms = idle_ms,
                duration_ms = duration_ms,
                points = g.points,
                finger = finger,
              }
              active[finger] = nil
            end
          end
        end
        pending_us = 0
      elseif line ~= "" then
        ignored = ignored + 1
      end
    end
  end
  f:close()

  for _ in pairs(active) do ignored = ignored + 1 end
  return gestures, ignored
end

local function emit_sleep(out, ms)
  ms = math.max(0, round(ms))
  while ms > 0 do
    local chunk = math.min(ms, MAX_ACTION_MS)
    out[#out + 1] = string.format("must(nk.sleep(%d))", chunk)
    ms = ms - chunk
  end
end

local function export_lua(raw_path, out_path)
  local gestures, ignored_or_err = parse_raw(raw_path)
  if not gestures then return nil, ignored_or_err end
  local ignored = ignored_or_err or 0

  local out = {
    "-- Generated by NKTouch Recorder V2 v" .. VERSION,
    "-- Source: " .. clean_comment(raw_path),
    "-- Raw keyboard typing is intentionally replayed as physical taps; it is not guessed as semantic text.",
    "local nk = require(\"nktouch\")",
    "local function must(value, err)",
    "  if value == nil or value == false then error(err or \"NKTouch action failed\", 2) end",
    "  return value",
    "end",
    "",
  }

  local counts = {tap = 0, hold = 0, swipe = 0}
  for i, g in ipairs(gestures) do
    if g.idle_ms > 0 then emit_sleep(out, g.idle_ms) end
    out[#out + 1] = string.format("-- gesture %d • finger %s • raw points %d", i, g.finger, g.points)
    if g.action == "tap" then
      counts.tap = counts.tap + 1
      out[#out + 1] = string.format("must(nk.tap(%.1f, %.1f))", g.x1, g.y1)
    elseif g.action == "hold" then
      counts.hold = counts.hold + 1
      local ms = math.min(math.max(1, g.duration_ms), MAX_ACTION_MS)
      out[#out + 1] = string.format("must(nk.hold(%.1f, %.1f, %d))", g.x1, g.y1, ms)
      if g.duration_ms > MAX_ACTION_MS then
        out[#out + 1] = string.format("-- original hold was %d ms; clamped to native safety limit", g.duration_ms)
      end
    else
      counts.swipe = counts.swipe + 1
      local ms = math.min(math.max(32, g.duration_ms), MAX_ACTION_MS)
      out[#out + 1] = string.format("must(nk.swipe(%.1f, %.1f, %.1f, %.1f, %d))", g.x1, g.y1, g.x2, g.y2, ms)
      if g.duration_ms > MAX_ACTION_MS then
        out[#out + 1] = string.format("-- original swipe was %d ms; clamped to native safety limit", g.duration_ms)
      end
    end
    out[#out + 1] = ""
  end

  out[#out + 1] = string.format("-- gestures=%d tap=%d hold=%d swipe=%d ignored=%d", #gestures, counts.tap, counts.hold, counts.swipe, ignored)

  local f, err = io.open(out_path, "w")
  if not f then return nil, "cannot write Lua file: " .. tostring(err) end
  f:write(table.concat(out, "\n"), "\n")
  f:close()

  return {
    gestures = #gestures,
    tap = counts.tap,
    hold = counts.hold,
    swipe = counts.swipe,
    ignored = ignored,
    output = out_path,
  }
end

local function main(argv)
  if argv[1] == "version" then
    print(VERSION)
    return 0
  end
  if argv[1] ~= "export" or not argv[2] or not argv[3] or argv[4] then
    io.stderr:write("usage: nkrecorder.lua export <recording.raw> <output.lua>\n")
    return 2
  end
  local result, err = export_lua(argv[2], argv[3])
  if not result then
    io.stderr:write("nkrecorder: ", tostring(err), "\n")
    return 3
  end
  print(string.format("output=%s", result.output))
  print(string.format("gestures=%d", result.gestures))
  print(string.format("tap=%d", result.tap))
  print(string.format("hold=%d", result.hold))
  print(string.format("swipe=%d", result.swipe))
  print(string.format("ignored=%d", result.ignored))
  return 0
end

local invoked_as_script = arg and type(arg[0]) == "string" and arg[0]:match("nkrecorder%.lua$")
if invoked_as_script then os.exit(main(arg)) end

return {
  VERSION = VERSION,
  parseRaw = parse_raw,
  exportLua = export_lua,
}
